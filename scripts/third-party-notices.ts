// Writes the licence texts of the Rust crates and npm packages Harmony ships.
// The file lands in the Web Client, so the Music Server and the Desktop Client
// both carry it. `--check` fails when it is out of date.
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

export type Dependency = { name: string; license: string; texts: string[] };

const repoRoot = resolve(import.meta.dirname, "..");
const output = join(repoRoot, "web/public/third-party-notices.txt");
const licenseFile = /^(licen[cs]e|copying|copyright|notice|unlicense)/i;
const maxBuffer = 1 << 30;

/** Lists each dependency once and each licence text once, in a stable order. */
export function renderNotices(dependencies: Dependency[]): string {
	const sorted = dependencies.toSorted((a, b) => a.name.localeCompare(b.name));
	const holders = new Map<string, string[]>();
	for (const { name, texts } of sorted) {
		for (const text of texts) {
			holders.set(text, [...(holders.get(text) ?? []), name]);
		}
	}
	const index = sorted.map(({ name, license }) => `${name}: ${license}`);
	const sections = [...holders]
		.sort(([, a], [, b]) => a[0].localeCompare(b[0]))
		.map(
			([text, names]) => `${"-".repeat(72)}\n${names.join(", ")}\n\n${text}`,
		);
	return `Third-party software in Harmony

Generated by scripts/third-party-notices.ts. FFmpeg, mpv and the libraries that
ship beside them are covered in the licenses folder of the repository.

${index.join("\n")}

${sections.join("\n\n")}
`;
}

function licenseTexts(directory: string): string[] {
	return readdirSync(directory)
		.filter((name) => licenseFile.test(name))
		.sort()
		.map((name) => join(directory, name))
		.filter((path) => statSync(path).isFile())
		.map((path) => readFileSync(path, "utf8").replaceAll("\r\n", "\n").trim());
}

type CargoPackage = {
	name: string;
	version: string;
	source: string | null;
	license: string | null;
	manifest_path: string;
};

function crates(): Dependency[] {
	const metadata = JSON.parse(
		execFileSync("cargo", ["metadata", "--format-version=1", "--locked"], {
			cwd: repoRoot,
			encoding: "utf8",
			maxBuffer,
		}),
	) as { packages: CargoPackage[] };
	return metadata.packages
		.filter((crate) => crate.source !== null)
		.map((crate) => ({
			name: `${crate.name} ${crate.version}`,
			license: crate.license ?? "see its licence text",
			texts: licenseTexts(dirname(crate.manifest_path)),
		}));
}

type PnpmPackage = { name: string; versions: string[]; paths: string[] };

function npmPackages(): Dependency[] {
	const listed = JSON.parse(
		execFileSync("pnpm", ["-r", "licenses", "list", "--prod", "--json"], {
			cwd: repoRoot,
			encoding: "utf8",
			maxBuffer,
		}),
	) as Record<string, PnpmPackage[]>;
	return Object.entries(listed).flatMap(([license, packages]) =>
		packages.flatMap(({ name, versions, paths }) =>
			paths
				.map((path, index) => ({
					name: `${name} ${versions[index]}`,
					license,
					path,
				}))
				.filter(({ path }) => path.includes("node_modules"))
				.map(({ path, ...dependency }) => ({
					...dependency,
					texts: licenseTexts(path),
				})),
		),
	);
}

if (import.meta.main) {
	const notices = renderNotices([...crates(), ...npmPackages()]);
	if (!process.argv.includes("--check")) {
		writeFileSync(output, notices);
	} else if (readFileSync(output, "utf8") !== notices) {
		throw new Error(`${output} is stale; run 'mise run generate'.`);
	}
}
